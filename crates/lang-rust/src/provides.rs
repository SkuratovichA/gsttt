//! What a Rust project reports to coverage: the contracts its packs find, and in words what it cannot see.

#[cfg(test)]
mod tests;

use std::collections::{BTreeMap, BTreeSet};

use gsttt_core::connector::Provide;
use gsttt_core::contract::{ContractKind, Role};
use gsttt_core::rules::Pack;

/// Something the connector cannot see, filed under the contract it would have found. Every project reports all of
/// them, with or without a pack for that contract: an answer that says nothing about gRPC would pass for one that
/// looked and found none.
struct Gap {
    kind: ContractKind,
    role: Role,
    text: &'static str,
}

/// What applies to every contract, because it is true of the files before it is true of any contract: nothing here
/// reads a dependency, expands a macro or runs a build script. The sentence about generated code comes last.
const EVERYWHERE: [&str; 5] = [
    "names that a glob import brings in, such as `prop` after `use proptest::prelude::*`, are not known: a path that starts with one is reported as an unknown package",
    "a crate target with more than 10000 modules is read up to that many, and a path into the modules past the cut stops at the deepest module before it",
    "a module declared twice under different `cfg`s, such as `unix.rs` and `win.rs` behind one `mod sys;`, is the first declaration to every path that names it: the other file resolves its own `crate::`, `self::` and `super::` paths, and no path reaches it by name",
    "paths written inside `macro_rules!` bodies are not read",
    "items generated by macros, such as modules and routes, and code included with `include!` from generated files are not read",
];

static GAPS: [Gap; 9] = [
    Gap {
        kind: ContractKind::Http,
        role: Role::Serves,
        text: "actix `configure`: the routes a function registers on a `ServiceConfig` keep the path they are written with, because the function is not followed to the scope that applies it",
    },
    Gap {
        kind: ContractKind::Http,
        role: Role::Serves,
        text: "routers passed as values the connector cannot follow: a router built in another crate, re-exported with `pub use`, kept in a field, handed over as an argument, returned from a branch or mounted with `nest_service` is not placed under the prefix it is mounted at",
    },
    Gap {
        kind: ContractKind::Http,
        role: Role::Serves,
        text: "router mounts are followed only to a limit: routers nested more than 64 deep, or entered more than 50000 times in the walk from one router that nothing mounts, are not followed past it, and the routes below the cut keep the paths they are written with",
    },
    Gap {
        kind: ContractKind::Http,
        role: Role::Serves,
        text: "mounts written `Type::router()`: only `Self::name`, a function of the file and a path to a function of a module are followed, so the routes of a router built by an associated function of a type keep the paths they are written with",
    },
    Gap {
        kind: ContractKind::Http,
        role: Role::Calls,
        text: "clients passed as values the connector cannot follow: a request through a client returned by another function, or declared with a type alias that hides its name, is not read, and neither is a URL with no literal path",
    },
    Gap {
        kind: ContractKind::Grpc,
        role: Role::Serves,
        text: "tonic services: a gRPC server implemented for a generated trait is not read",
    },
    Gap {
        kind: ContractKind::Table,
        role: Role::Declares,
        text: "Diesel `table!`: a table declared with the macro is not read",
    },
    Gap {
        kind: ContractKind::Table,
        role: Role::Calls,
        text: "SQL put together at run time is not read, and neither are queries written with the Diesel or SeaORM builders, which name tables through types",
    },
    Gap {
        kind: ContractKind::Env,
        role: Role::Calls,
        text: "variable names built at run time",
    },
];

/// One line of the report while it is being put together.
#[derive(Default)]
struct Entry<'a> {
    via: BTreeSet<&'a str>,
    blind_spots: Vec<&'static str>,
}

/// What a project whose manifest switched on `packs` provides. The list is in the order of the contracts, so the same
/// project reports the same list on every run.
pub(crate) fn provides(packs: &[Pack]) -> Vec<Provide> {
    let mut entries: BTreeMap<(ContractKind, Role), Entry<'_>> = BTreeMap::new();
    for pack in packs {
        for contract in found_by(pack) {
            entries.entry(contract).or_default().via.insert(&pack.name);
        }
    }
    for gap in &GAPS {
        entries
            .entry((gap.kind.clone(), gap.role))
            .or_default()
            .blind_spots
            .push(gap.text);
    }
    entries
        .into_iter()
        .map(|((kind, role), entry)| Provide {
            kind,
            role,
            via: entry.via.into_iter().map(str::to_owned).collect(),
            blind_spots: entry
                .blind_spots
                .into_iter()
                .chain(EVERYWHERE)
                .map(str::to_owned)
                .collect(),
        })
        .collect()
}

/// The contracts the rules of `pack` name, with the role each gives them.
fn found_by(pack: &Pack) -> impl Iterator<Item = (ContractKind, Role)> + '_ {
    let calls = pack.calls.iter().map(|rule| (rule.kind.clone(), rule.role));
    let decorators = pack
        .decorators
        .iter()
        .map(|rule| (rule.kind.clone(), rule.role));
    let chains = pack
        .chains
        .iter()
        .map(|rule| (rule.kind.clone(), rule.role));
    let assigns = pack
        .assigns
        .iter()
        .map(|rule| (rule.kind.clone(), rule.role));
    // The connector for the document's language reads what it holds. An embedded query is something the code runs,
    // so it calls the contract.
    let embeds = pack
        .embeds
        .iter()
        .map(|rule| (embedded(&rule.lang), Role::Calls));
    calls
        .chain(decorators)
        .chain(chains)
        .chain(assigns)
        .chain(embeds)
}

/// The contract that a document of language `lang`, as the connector for it names the language in `embeds`, holds.
fn embedded(lang: &str) -> ContractKind {
    match lang {
        "sql" => ContractKind::Table,
        "graphql" => ContractKind::Graphql,
        other => ContractKind::Other(other.to_owned()),
    }
}
