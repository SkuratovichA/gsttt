//! Editor support: the `LuaLS` annotations of the `gsttt` module, the language server settings that point at them, and the starter `init.lua`. `gsttt init` writes all three.
//!
//! The annotations are generated from the option schemas the modules already publish, so an option added to a module reaches the editor without a second place to edit.

use std::collections::{BTreeMap, BTreeSet};

use gsttt_core::connector::DynConnector;
use gsttt_core::rules::Pack;
use gsttt_core::setup::ExternalSetup;
use schemars::schema_for;
use serde_json::{Map, Value, json};

use crate::evaluate::{MODULES, SetupOptions};

/// Where `gsttt init` writes the annotations, relative to the repository root.
pub const ANNOTATIONS_PATH: &str = ".gsttt/types/gsttt.lua";

/// Where `gsttt init` writes the language server settings, relative to the repository root.
pub const LUARC_PATH: &str = ".gsttt/.luarc.json";

/// The folder of the annotations, which the language server reads as a library.
const TYPES_DIR: &str = ".gsttt/types";

/// The folder the language server has to be opened in, relative to the repository root. It reads [`LUARC_PATH`] from the root of the folder it is opened in and from nowhere else, so the paths in the settings start here, not at the repository root.
const WORKSPACE: &str = ".gsttt";

/// The annotations of the functions of the `gsttt` module besides the one per registry module, in the order of `FUNCTIONS` in `evaluate.rs`.
const SIGNATURES: [&str; 5] = [
    "---Sets what is not about one module: files to leave out, route prefixes, the size limit and whether detection turns modules on. A key that is not given keeps its value.\n---@param options? gsttt.SetupOptions\nfunction gsttt.setup(options) end",
    "---Leaves a module off even when detection finds it.\n---@param name gsttt.Module\nfunction gsttt.disable(name) end",
    "---Adds a rule pack. A pack of the same name is an error.\n---@param pack gsttt.Pack\nfunction gsttt.pack(pack) end",
    "---Turns off a built-in rule pack by its name, like `axios`.\n---@param name string\nfunction gsttt.disable_pack(name) end",
    "---Declares a connector that runs as a command and reads the files its globs match.\n---@param external gsttt.External\nfunction gsttt.external(external) end",
];

/// The `LuaLS` annotations of the `gsttt` module for the modules of `registry`: one function per module that takes its options class, the options classes with a field per property, and the types of `setup`, `pack` and `external`.
///
/// A module whose name is not a Lua identifier has no function here, because `gsttt.lang-ts` does not parse; the output does not depend on the order of `registry`.
#[must_use]
pub fn annotations(registry: &[&dyn DynConnector]) -> String {
    let mut modules: Vec<Module> = registry
        .iter()
        .filter_map(|connector| module(*connector))
        .collect();
    modules.sort_by_key(|module| module.name);

    let mut declarations = Declarations::default();
    for module in &modules {
        declarations.add(
            &module.namespace,
            &format!("{}Options", module.namespace),
            &module.options,
        );
    }
    declarations.add(
        "Setup",
        "SetupOptions",
        schema_for!(SetupOptions).as_value(),
    );
    declarations.add(
        "External",
        "External",
        schema_for!(ExternalSetup).as_value(),
    );
    declarations.add("", "Pack", schema_for!(Pack).as_value());

    let mut blocks = vec![
        "---@meta gsttt".to_owned(),
        "-- Generated by `gsttt init` from the modules this binary ships. Edit .gsttt/init.lua, not this file.".to_owned(),
        module_names(&modules),
    ];
    blocks.extend(declarations.0.into_values());
    blocks.push("---@class gsttt\nlocal gsttt = {}".to_owned());
    blocks.extend(modules.iter().map(function));
    blocks.extend(SIGNATURES.map(str::to_owned));
    blocks.push("return gsttt".to_owned());
    let mut text = blocks.join("\n\n");
    text.push('\n');
    text
}

/// The settings `LuaLS` reads from [`LUARC_PATH`]: Lua 5.4, the annotations as a library and `.gsttt/lua/` on the path `require` searches, so a local module completes and checks like the config does.
///
/// `LuaLS` reads the file only when `.gsttt/` is the folder it is opened in, so the paths are relative to `.gsttt/`, not to the repository root. The file is JSON and cannot say so itself; the starter `init.lua` does.
#[must_use]
pub fn luarc() -> String {
    let modules = in_workspace(MODULES);
    let settings = json!({
        "$schema": "https://raw.githubusercontent.com/LuaLS/vscode-lua/master/setting/schema.json",
        "runtime.version": "Lua 5.4",
        "runtime.path": [format!("{modules}/?.lua"), format!("{modules}/?/init.lua")],
        "workspace.library": [in_workspace(TYPES_DIR)],
    });
    format!("{settings:#}\n")
}

/// `path`, which is under [`WORKSPACE`] and given from the repository root, as the settings write it: from the workspace.
fn in_workspace(path: &str) -> &str {
    path.strip_prefix(WORKSPACE)
        .and_then(|rest| rest.strip_prefix('/'))
        .unwrap_or(path)
}

/// The first `.gsttt/init.lua`: a note on where to open an editor, the line that loads the module, and the `detected` modules as comments to uncomment when one needs options. Detected modules run with their defaults without any line, so the starter changes nothing.
#[must_use]
pub fn starter(detected: &[&str]) -> String {
    let mut names = detected.to_vec();
    names.sort_unstable();
    names.dedup();

    let mut lines = vec![
        format!(
            "-- To have an editor complete and check this file, open the {WORKSPACE} folder as the workspace: lua-language-server reads .luarc.json only from the root of the folder it is opened in."
        ),
        String::new(),
        "local g = require(\"gsttt\")".to_owned(),
        String::new(),
    ];
    if names.is_empty() {
        lines.push("-- No module was detected in this repository. Turn one on by calling it, like g.ts {}.".to_owned());
    } else {
        lines.push("-- Detected in this repository. Each runs with its defaults; uncomment a line to give it options.".to_owned());
        lines.extend(names.iter().map(|name| format!("-- g.{name} {{}}")));
    }
    let mut text = lines.join("\n");
    text.push('\n');
    text
}

/// A registry module as the annotations see it.
struct Module {
    name: &'static str,
    summary: &'static str,
    /// The name in the class names: `ts` is `Ts`.
    namespace: String,
    options: Value,
}

fn module(connector: &dyn DynConnector) -> Option<Module> {
    let meta = connector.meta();
    if !is_identifier(meta.name) {
        tracing::warn!(
            module = meta.name,
            "no annotation for a module whose name is not a Lua identifier"
        );
        return None;
    }
    let namespace = pascal(meta.name);
    let mut options = connector.options_schema().as_value().clone();
    if let Some(schema) = options.as_object_mut() {
        schema.entry("description").or_insert_with(|| {
            Value::String(format!("The options of the `{}` module.", meta.name))
        });
    }
    Some(Module {
        name: meta.name,
        summary: meta.summary,
        namespace,
        options,
    })
}

/// The alias that names the modules `disable` takes.
fn module_names(modules: &[Module]) -> String {
    if modules.is_empty() {
        return "---@alias gsttt.Module string".to_owned();
    }
    let names: Vec<String> = modules
        .iter()
        .map(|module| format!("\"{}\"", module.name))
        .collect();
    format!("---@alias gsttt.Module {}", names.join("|"))
}

/// The function that turns a module on.
fn function(module: &Module) -> String {
    let summary = module.summary.trim_end_matches('.');
    format!(
        "---Turns on `{name}` ({summary}). Without options it runs with its defaults.\n---@param options? gsttt.{class}Options\nfunction gsttt.{name}(options) end",
        name = module.name,
        class = module.namespace,
    )
}

fn is_identifier(name: &str) -> bool {
    let mut chars = name.chars();
    chars
        .next()
        .is_some_and(|first| first.is_ascii_alphabetic() || first == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// `ts` is `Ts`, `graphql-schema` is `GraphqlSchema`.
fn pascal(name: &str) -> String {
    let mut text = String::new();
    for part in name.split(|c: char| !c.is_ascii_alphanumeric()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            text.push(first.to_ascii_uppercase());
            text.push_str(chars.as_str());
        }
    }
    text
}

/// What the annotation file declares, by Lua name: a class for a record, an alias for any other type. A map keeps them sorted.
#[derive(Default)]
struct Declarations(BTreeMap<String, String>);

impl Declarations {
    /// Declares `schema` as `gsttt.<name>` and every definition it points at as `gsttt.<namespace><Definition>`, so two schemas that define the same name cannot clash.
    fn add(&mut self, namespace: &str, name: &str, schema: &Value) {
        let mut walk = Walk {
            namespace,
            definitions: schema.get("$defs").and_then(Value::as_object),
            queue: Vec::new(),
            queued: BTreeSet::new(),
        };
        let root = format!("gsttt.{name}");
        let text = walk.declare(&root, schema);
        self.declare(root, text);
        while let Some(definition) = walk.queue.pop() {
            let name = format!("gsttt.{namespace}{definition}");
            let text = match walk
                .definitions
                .and_then(|definitions| definitions.get(definition.as_str()))
            {
                Some(schema) => walk.declare(&name, schema),
                None => format!("---@alias {name} any"),
            };
            self.declare(name, text);
        }
    }

    /// Keeps the first text for a name: a second, different one means two schemas share a name, which the namespaces are there to prevent.
    fn declare(&mut self, name: String, text: String) {
        if let Some(first) = self.0.get(&name) {
            if *first != text {
                tracing::warn!(
                    name,
                    "two different declarations share a name; the first one stays"
                );
            }
            return;
        }
        self.0.insert(name, text);
    }
}

/// Turns the schemas of one root into declarations and type expressions, collecting the definitions they point at.
struct Walk<'a> {
    namespace: &'a str,
    definitions: Option<&'a Map<String, Value>>,
    /// Definitions pointed at and not declared yet.
    queue: Vec<String>,
    queued: BTreeSet<String>,
}

/// The named properties of an object schema and which of them must be given.
struct Record<'a> {
    properties: Vec<(&'a String, &'a Value)>,
    required: BTreeSet<&'a str>,
}

impl Walk<'_> {
    /// The declaration of `schema` under the Lua name `name`: its description, then a class with a field per property or an alias.
    fn declare(&mut self, name: &str, schema: &Value) -> String {
        let mut lines: Vec<String> = describe(schema)
            .lines()
            .map(|line| format!("---{}", line.trim_end()))
            .collect();
        let record = schema
            .as_object()
            .filter(|object| is_object(object))
            .and_then(record);
        let Some(record) = record else {
            let kind = self.field_type(schema, false);
            lines.push(format!("---@alias {name} {kind}"));
            return lines.join("\n");
        };
        lines.push(format!("---@class {name}"));
        for (key, property) in record.properties {
            let optional = !record.required.contains(key.as_str());
            let kind = self.field_type(property, optional);
            let mark = if optional { "?" } else { "" };
            let note = one_line(describe(property));
            let tail = if note.is_empty() {
                note
            } else {
                format!(" {note}")
            };
            lines.push(format!("---@field {key}{mark} {kind}{tail}"));
        }
        lines.join("\n")
    }

    /// The type of a property. An optional one is `nil` anyway, which the `?` on its name says.
    fn field_type(&mut self, schema: &Value, optional: bool) -> String {
        let mut kinds = self.alternatives(schema);
        if optional {
            kinds.retain(|kind| kind != "nil");
        }
        if kinds.is_empty() {
            return "any".to_owned();
        }
        kinds.join("|")
    }

    /// The types a value of `schema` can have, without repeats and in the order the schema names them.
    fn alternatives(&mut self, schema: &Value) -> Vec<String> {
        let Some(object) = schema.as_object() else {
            return vec!["any".to_owned()];
        };
        let mut found = Vec::new();
        if let Some(Value::String(pointer)) = object.get("$ref") {
            found.push(self.reference(pointer));
        } else if let Some(value) = object.get("const") {
            found.push(literal(value));
        } else if let Some(Value::Array(values)) = object.get("enum") {
            found.extend(values.iter().map(literal));
        } else if let Some(Value::Array(branches)) =
            object.get("oneOf").or_else(|| object.get("anyOf"))
        {
            for branch in branches {
                found.extend(self.alternatives(branch));
            }
        } else {
            found.extend(self.typed(object));
        }
        let mut seen = BTreeSet::new();
        found.retain(|kind| seen.insert(kind.clone()));
        found
    }

    /// The types a schema names with `type`, or `any` when it names none.
    fn typed(&mut self, object: &Map<String, Value>) -> Vec<String> {
        let names: Vec<&str> = match object.get("type") {
            Some(Value::String(name)) => vec![name.as_str()],
            Some(Value::Array(names)) => names.iter().filter_map(Value::as_str).collect(),
            _ if object.contains_key("properties") => vec!["object"],
            _ => Vec::new(),
        };
        if names.is_empty() {
            return vec!["any".to_owned()];
        }
        let mut found = Vec::new();
        for name in names {
            found.push(match name {
                "string" | "integer" | "number" | "boolean" => name.to_owned(),
                "null" => "nil".to_owned(),
                "array" => self.array(object),
                "object" => self.object(object),
                _ => "any".to_owned(),
            });
        }
        found
    }

    /// `T[]` for a list, `[A, B]` for a tuple.
    fn array(&mut self, object: &Map<String, Value>) -> String {
        if let Some(Value::Array(items)) = object.get("prefixItems") {
            let mut kinds = Vec::new();
            for item in items {
                kinds.push(self.field_type(item, false));
            }
            return format!("[{}]", kinds.join(", "));
        }
        let element = match object.get("items") {
            Some(items) => self.alternatives(items),
            None => Vec::new(),
        };
        match element.as_slice() {
            [] => "any[]".to_owned(),
            [only] => format!("{only}[]"),
            many => format!("({})[]", many.join("|")),
        }
    }

    /// A table type: `{ key: T }` for named properties, `table<string, T>` for a map.
    fn object(&mut self, object: &Map<String, Value>) -> String {
        if let Some(record) = record(object) {
            if record.properties.is_empty() {
                return "table".to_owned();
            }
            let mut fields = Vec::new();
            for (key, property) in record.properties {
                let optional = !record.required.contains(key.as_str());
                let mark = if optional { "?" } else { "" };
                fields.push(format!(
                    "{key}{mark}: {}",
                    self.field_type(property, optional)
                ));
            }
            return format!("{{ {} }}", fields.join(", "));
        }
        let values = match object.get("additionalProperties") {
            Some(schema @ Value::Object(_)) => self.field_type(schema, false),
            _ => "any".to_owned(),
        };
        format!("table<string, {values}>")
    }

    /// The Lua name of the definition a `$ref` points at, which is declared once this root is done.
    fn reference(&mut self, pointer: &str) -> String {
        let Some(definition) = pointer.strip_prefix("#/$defs/") else {
            return "any".to_owned();
        };
        if self.queued.insert(definition.to_owned()) {
            self.queue.push(definition.to_owned());
        }
        format!("gsttt.{}{definition}", self.namespace)
    }
}

/// Whether a schema says its values are objects, and nothing else.
fn is_object(object: &Map<String, Value>) -> bool {
    match object.get("type") {
        Some(Value::String(name)) => name == "object",
        Some(_) => false,
        None => object.contains_key("properties"),
    }
}

/// The properties of an object schema, sorted by name; `None` for a map from any name to one type, which is a table and not a class.
fn record(object: &Map<String, Value>) -> Option<Record<'_>> {
    let properties = object.get("properties").and_then(Value::as_object);
    if properties.is_none() && matches!(object.get("additionalProperties"), Some(Value::Object(_)))
    {
        return None;
    }
    let mut properties: Vec<_> = properties
        .map(|map| map.iter().collect())
        .unwrap_or_default();
    properties.sort_by_key(|(name, _)| *name);
    let required = object
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    Some(Record {
        properties,
        required,
    })
}

/// The Lua form of a constant of a schema.
fn literal(value: &Value) -> String {
    match value {
        Value::Null => "nil".to_owned(),
        other => other.to_string(),
    }
}

fn describe(schema: &Value) -> &str {
    schema
        .get("description")
        .and_then(Value::as_str)
        .map_or("", str::trim)
}

/// A description on one line, because an annotation ends where its line does.
fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    fn declared(schema: &Value) -> String {
        let mut declarations = Declarations::default();
        declarations.add("Test", "Root", schema);
        declarations.0.into_values().collect::<Vec<_>>().join("\n")
    }

    #[test]
    fn enums_lists_maps_tuples_and_references_become_lua_types() {
        let text = declared(&json!({
            "type": "object",
            "properties": {
                "mode": {"description": "How\nto go.", "type": "string", "enum": ["fast", "slow"]},
                "names": {"type": "array", "items": {"type": ["string", "null"]}},
                "by_name": {"type": "object", "additionalProperties": {"type": "integer"}},
                "pair": {"type": "array", "prefixItems": [{"type": "string"}, {"type": "integer"}]},
                "rule": {"$ref": "#/$defs/Rule"},
                "either": {"oneOf": [{"const": "a"}, {"const": "b"}]},
                "inline": {"type": "object", "properties": {"x": {"type": "number"}}, "required": ["x"]}
            },
            "required": ["mode"],
            "$defs": {"Rule": {"type": "object", "properties": {"pattern": {"type": "string"}}, "required": ["pattern"]}}
        }));
        let expected = [
            "---@class gsttt.Root",
            "---@field by_name? table<string, integer>",
            "---@field either? \"a\"|\"b\"",
            "---@field inline? { x: number }",
            "---@field mode \"fast\"|\"slow\" How to go.",
            "---@field names? (string|nil)[]",
            "---@field pair? [string, integer]",
            "---@field rule? gsttt.TestRule",
            "---@class gsttt.TestRule",
            "---@field pattern string",
        ]
        .join("\n");
        assert_eq!(text, expected);
    }

    #[test]
    fn a_definition_that_points_at_itself_is_declared_once() {
        let text = declared(&json!({
            "$ref": "#/$defs/Node",
            "$defs": {"Node": {"description": "A node.", "type": "object", "properties": {"children": {"type": "array", "items": {"$ref": "#/$defs/Node"}}}}}
        }));
        let expected = [
            "---@alias gsttt.Root gsttt.TestNode",
            "---A node.",
            "---@class gsttt.TestNode",
            "---@field children? gsttt.TestNode[]",
        ]
        .join("\n");
        assert_eq!(text, expected);
    }

    #[test]
    fn pascal_joins_the_parts_of_a_name() {
        assert_eq!(pascal("ts"), "Ts");
        assert_eq!(pascal("graphql-schema"), "GraphqlSchema");
        assert_eq!(pascal("open_api"), "OpenApi");
    }

    #[test]
    fn every_function_of_the_module_is_annotated() {
        for name in crate::evaluate::FUNCTIONS {
            let declared = SIGNATURES
                .iter()
                .any(|block| block.contains(&format!("\nfunction gsttt.{name}(")));
            assert!(declared, "gsttt.{name} has no annotation");
        }
        assert_eq!(SIGNATURES.len(), crate::evaluate::FUNCTIONS.len());
    }

    #[test]
    fn the_annotations_live_in_the_folder_the_language_server_reads() {
        assert_eq!(ANNOTATIONS_PATH.strip_prefix(TYPES_DIR), Some("/gsttt.lua"));
    }

    #[test]
    fn everything_the_settings_name_lives_in_the_workspace() {
        // `in_workspace` hands back a path it cannot shorten as it is, so a folder that left `.gsttt/` would put a path from the repository root into the settings without a sound; this is the sound.
        for path in [
            LUARC_PATH,
            ANNOTATIONS_PATH,
            TYPES_DIR,
            MODULES,
            crate::evaluate::INIT_PATH,
        ] {
            assert!(
                path.strip_prefix(WORKSPACE)
                    .is_some_and(|rest| rest.starts_with('/')),
                "{path} is not under {WORKSPACE}/"
            );
        }
        assert_eq!(in_workspace(MODULES), "lua");
        assert_eq!(in_workspace(TYPES_DIR), "types");
        assert_eq!(in_workspace(".gsttt-other/lua"), ".gsttt-other/lua");
    }
}
