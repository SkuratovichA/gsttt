//! `gsttt init`: the starter config, and the JSON Schemas an editor checks the config and the packs with.

use std::fs::{self, OpenOptions};
use std::io::{self, Write as _};

use camino::Utf8Path;
use gsttt_config::{
    CONFIG_PATH, CONFIG_SCHEMA_PATH, PACK_SCHEMA_PATH, config_schema, pack_schema, starter,
};
use gsttt_core::Setup;
use gsttt_core::engine::refresh::Engine;
use serde_json::{Map, Value};

use super::print;
use crate::cli::Flags;
use crate::error::CliError;
use crate::registry::Registry;
use crate::repository::RepositoryError;
use crate::root;
use crate::streams::{Io, Outcome};

/// What a schema says about itself, in the `$comment` at its top.
const GENERATED: &str = "Generated by `gsttt init` from the connectors of this build of gsttt. Edits to this file are lost the next time it runs.";

/// `gsttt init`: writes `.gsttt/config.toml` when there is none, and the two schemas always, and says for each file whether it wrote or kept it.
///
/// The root is found like any command finds it, but the config is not read: `init` has to work beside a config that does not parse, and a repository that has none. The modules the starter names are the built-in connectors that find a project in the tree, which the engine learns from the same listing a refresh uses. It prints plain text under `--json` too, because it has no answer to give but the list of files.
pub(super) fn init(flags: &Flags, io: &mut Io<'_>) -> Result<Outcome, CliError> {
    let workspace = root::locate(&root::start(flags.directory.as_deref())?)?;
    let registry = Registry::builtin().map_err(RepositoryError::from)?;
    let connectors = registry.connectors();
    let setup = Setup::default();
    let detected = Engine::new(workspace.clone(), &connectors, registry.packs(), &setup)
        .detected()
        .map_err(RepositoryError::from)?;

    let root = workspace.root();
    put(io, root, CONFIG_PATH, &starter(&detected), Existing::Keep)?;
    let schema = generated(config_schema(&connectors));
    put(io, root, CONFIG_SCHEMA_PATH, &schema, Existing::Replace)?;
    put(
        io,
        root,
        PACK_SCHEMA_PATH,
        &generated(pack_schema()),
        Existing::Replace,
    )?;
    Ok(Outcome::Answered)
}

/// What happens to a file that is already there.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Existing {
    /// It stays as it is, because a person may have edited it.
    Keep,
    /// It is replaced, because `init` generated it.
    Replace,
}

/// Writes `text` to `path` under `root` as `existing` says, and tells whether the file was written or kept.
fn put(
    io: &mut Io<'_>,
    root: &Utf8Path,
    path: &str,
    text: &str,
    existing: Existing,
) -> Result<(), CliError> {
    let file = root.join(path);
    let wrote =
        write(&file, text, existing).map_err(|source| CliError::Init { path: file, source })?;
    let told = if wrote { "wrote" } else { "kept" };
    io.answer(format!("{told} {path}\n").as_bytes())
}

/// Makes `file` hold `text`, with the folders above it, and returns whether it did. A file that is there is left alone under [`Existing::Keep`], and removed first under [`Existing::Replace`], so that a link in its place is replaced and never written through. The file is made with `create_new`, which does not follow a link either, and keeps the permissions the user's umask gives any new file.
fn write(file: &Utf8Path, text: &str, existing: Existing) -> io::Result<bool> {
    if let Some(folder) = file.parent() {
        fs::create_dir_all(folder)?;
    }
    if existing == Existing::Replace
        && let Err(error) = fs::remove_file(file)
        && error.kind() != io::ErrorKind::NotFound
    {
        return Err(error);
    }
    match OpenOptions::new().write(true).create_new(true).open(file) {
        Ok(mut created) => created.write_all(text.as_bytes()).map(|()| true),
        Err(error)
            if existing == Existing::Keep && error.kind() == io::ErrorKind::AlreadyExists =>
        {
            Ok(false)
        }
        Err(error) => Err(error),
    }
}

/// The text of a schema as `init` writes it: the schema with a `$comment` before the rest that says where it came from, in the form of [`print::indented`].
fn generated(schema: impl Into<Value>) -> String {
    let document = match schema.into() {
        Value::Object(object) => {
            let mut commented = Map::new();
            commented.insert("$comment".to_owned(), Value::from(GENERATED));
            commented.extend(object);
            Value::Object(commented)
        }
        other => other,
    };
    print::indented(&document)
}

#[cfg(test)]
mod tests {
    use serde_json::json;

    use super::*;

    #[test]
    fn a_generated_schema_has_its_comment_first_and_ends_in_a_line_break() {
        let text = generated(json!({ "type": "object", "title": "t" }));

        assert!(text.starts_with("{\n  \"$comment\": \"Generated by `gsttt init`"));
        assert!(text.ends_with("\n}\n"));
        let document: Value = serde_json::from_str(&text).unwrap();
        assert_eq!(document["type"], "object");
        assert_eq!(document["title"], "t");
    }

    #[test]
    fn a_generated_schema_is_the_same_text_every_time() {
        let schema = json!({ "b": 1, "a": [1, 2], "c": { "d": null } });

        assert_eq!(generated(schema.clone()), generated(schema));
    }
}
